-- =============================================================================
-- V15 : Product variants (size/colour combinations)
--
-- A variant is an optional refinement of a product: its own SKU and stock count,
-- and an optional price override. Most products never get one — the tables below
-- are purely additive, and every existing cart/order line keeps working with
-- variant_id left NULL.
--
-- Which attribute(s) a variant differs by (e.g. "Rəng", "Ölçü") is expressed by
-- reusing the existing attribute_options table rather than inventing a parallel
-- option system — a variant is simply a set of option picks.
-- =============================================================================

CREATE TABLE product_variants
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id         BIGINT         NOT NULL,
    sku                VARCHAR(80)    NOT NULL,
    price_override     NUMERIC(14, 2),
    track_stock        BOOLEAN        NOT NULL DEFAULT TRUE,
    stock_quantity     INTEGER        NOT NULL DEFAULT 0,
    allow_backorder    BOOLEAN        NOT NULL DEFAULT FALSE,
    image_media_id     BIGINT,
    sort_order         INTEGER        NOT NULL DEFAULT 0,
    is_default         BOOLEAN        NOT NULL DEFAULT FALSE,
    active             BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ,
    created_by         BIGINT,
    updated_by         BIGINT,

    CONSTRAINT fk_variant_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT fk_variant_image FOREIGN KEY (image_media_id) REFERENCES media_files (id) ON DELETE SET NULL,
    CONSTRAINT uq_variant_sku UNIQUE (sku)
);

CREATE INDEX idx_variants_product ON product_variants (product_id);

CREATE TABLE product_variant_options
(
    variant_id         BIGINT NOT NULL,
    attribute_option_id BIGINT NOT NULL,

    PRIMARY KEY (variant_id, attribute_option_id),
    CONSTRAINT fk_variant_option_variant FOREIGN KEY (variant_id) REFERENCES product_variants (id) ON DELETE CASCADE,
    CONSTRAINT fk_variant_option_option FOREIGN KEY (attribute_option_id) REFERENCES attribute_options (id) ON DELETE CASCADE
);

-- --- cart / order lines: which variant (if any) was picked -------------------

-- The old (cart_id, product_id) uniqueness must widen to include variant_id, so two
-- different variants of one product can each be their own line. NULLS NOT DISTINCT
-- keeps the guarantee for ordinary (non-variant) products, where variant_id is NULL —
-- without it, Postgres treats every NULL as distinct and the constraint would stop
-- preventing duplicate lines for the common case.
ALTER TABLE cart_items
    ADD COLUMN variant_id BIGINT,
    ADD CONSTRAINT fk_cart_item_variant FOREIGN KEY (variant_id) REFERENCES product_variants (id) ON DELETE SET NULL,
    DROP CONSTRAINT uq_cart_items,
    ADD CONSTRAINT uq_cart_items UNIQUE NULLS NOT DISTINCT (cart_id, product_id, variant_id);

-- order_items freezes everything by value (see V11) rather than a live FK, so a
-- variant deleted after purchase cannot corrupt order history — same treatment
-- product_sku/product_name already get.
ALTER TABLE order_items
    ADD COLUMN variant_id    BIGINT,
    ADD COLUMN variant_sku   VARCHAR(80),
    ADD COLUMN variant_label VARCHAR(255);

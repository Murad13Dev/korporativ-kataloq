CREATE TABLE post_categories
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug       VARCHAR(180) NOT NULL,
    color      VARCHAR(16),
    status     VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    sort_order INTEGER      NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    created_by BIGINT,
    updated_by BIGINT,

    CONSTRAINT uq_post_categories_slug UNIQUE (slug),
    CONSTRAINT ck_post_categories_status CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED'))
);

CREATE TABLE post_category_translations
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id   BIGINT       NOT NULL,
    language_code VARCHAR(8)   NOT NULL,
    name          VARCHAR(160) NOT NULL,
    description   VARCHAR(500),

    CONSTRAINT fk_post_cat_tr_category FOREIGN KEY (category_id) REFERENCES post_categories (id) ON DELETE CASCADE,
    CONSTRAINT fk_post_cat_tr_lang FOREIGN KEY (language_code) REFERENCES languages (code) ON DELETE CASCADE,
    CONSTRAINT uq_post_cat_tr UNIQUE (category_id, language_code)
);


CREATE TABLE posts
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id    BIGINT,
    author_id      BIGINT,
    cover_media_id BIGINT,
    slug           VARCHAR(180) NOT NULL,
    status         VARCHAR(16)  NOT NULL DEFAULT 'DRAFT',
    featured       BOOLEAN      NOT NULL DEFAULT FALSE,
    reading_minutes INTEGER,
    view_count     BIGINT       NOT NULL DEFAULT 0,
    published_at   TIMESTAMPTZ,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ,
    created_by     BIGINT,
    updated_by     BIGINT,
    deleted_at     TIMESTAMPTZ,

    CONSTRAINT fk_posts_category FOREIGN KEY (category_id) REFERENCES post_categories (id) ON DELETE SET NULL,
    CONSTRAINT fk_posts_author FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_posts_cover FOREIGN KEY (cover_media_id) REFERENCES media_files (id) ON DELETE SET NULL,
    CONSTRAINT ck_posts_status CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED'))
);

CREATE UNIQUE INDEX uq_posts_slug_alive ON posts (slug) WHERE deleted_at IS NULL;
CREATE INDEX idx_posts_status_published ON posts (status, published_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX idx_posts_category ON posts (category_id) WHERE deleted_at IS NULL;
CREATE INDEX idx_posts_featured ON posts (featured) WHERE deleted_at IS NULL AND featured;


CREATE TABLE post_translations
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id           BIGINT       NOT NULL,
    language_code     VARCHAR(8)   NOT NULL,
    title             VARCHAR(255) NOT NULL,
    short_description TEXT,
    content           TEXT,
    seo_title         VARCHAR(255),
    seo_description   VARCHAR(500),

    CONSTRAINT fk_post_tr_post FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_post_tr_lang FOREIGN KEY (language_code) REFERENCES languages (code) ON DELETE CASCADE,
    CONSTRAINT uq_post_tr UNIQUE (post_id, language_code)
);

CREATE INDEX idx_post_tr_title ON post_translations (language_code, title);


CREATE TABLE tags
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL,
    slug VARCHAR(180) NOT NULL,

    CONSTRAINT uq_tags_code UNIQUE (code),
    CONSTRAINT uq_tags_slug UNIQUE (slug)
);

CREATE TABLE tag_translations
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag_id        BIGINT       NOT NULL,
    language_code VARCHAR(8)   NOT NULL,
    name          VARCHAR(120) NOT NULL,

    CONSTRAINT fk_tag_tr_tag FOREIGN KEY (tag_id) REFERENCES tags (id) ON DELETE CASCADE,
    CONSTRAINT fk_tag_tr_lang FOREIGN KEY (language_code) REFERENCES languages (code) ON DELETE CASCADE,
    CONSTRAINT uq_tag_tr UNIQUE (tag_id, language_code)
);

CREATE TABLE post_tags
(
    post_id BIGINT NOT NULL,
    tag_id  BIGINT NOT NULL,

    PRIMARY KEY (post_id, tag_id),
    CONSTRAINT fk_post_tags_post FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_post_tags_tag FOREIGN KEY (tag_id) REFERENCES tags (id) ON DELETE CASCADE
);

CREATE INDEX idx_post_tags_tag ON post_tags (tag_id);



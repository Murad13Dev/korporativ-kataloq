CREATE TABLE contact_requests
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(160) NOT NULL,
    company_name     VARCHAR(160),
    email            VARCHAR(190) NOT NULL,
    phone            VARCHAR(40),
    subject          VARCHAR(190),
    message          TEXT         NOT NULL,
    -- CONTACT for the contact form, PRODUCT_INQUIRY when raised from a product page.
    request_type     VARCHAR(24)  NOT NULL DEFAULT 'CONTACT',
    product_id       BIGINT,
    status           VARCHAR(24)  NOT NULL DEFAULT 'NEW',
    admin_note       TEXT,
    handled_by       BIGINT,
    handled_at       TIMESTAMPTZ,
    privacy_accepted BOOLEAN      NOT NULL DEFAULT FALSE,
    source_url       VARCHAR(500),
    ip_address       VARCHAR(64),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ,
    created_by       BIGINT,
    updated_by       BIGINT,

    CONSTRAINT fk_contact_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE SET NULL,
    CONSTRAINT fk_contact_handler FOREIGN KEY (handled_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_contact_status CHECK (status IN ('NEW', 'IN_PROGRESS', 'ANSWERED', 'CLOSED', 'SPAM')),
    CONSTRAINT ck_contact_type CHECK (request_type IN ('CONTACT', 'PRODUCT_INQUIRY', 'QUOTE', 'SUPPORT', 'PARTNERSHIP'))
);

CREATE INDEX idx_contact_requests_status ON contact_requests (status, created_at DESC);
CREATE INDEX idx_contact_requests_email ON contact_requests (lower(email));
CREATE INDEX idx_contact_requests_product ON contact_requests (product_id);


CREATE TABLE newsletter_subscriptions
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(190) NOT NULL,
    name            VARCHAR(160),
    language_code   VARCHAR(8),
    status          VARCHAR(24)  NOT NULL DEFAULT 'PENDING',
    confirm_token   VARCHAR(128),
    confirmed_at    TIMESTAMPTZ,
    unsubscribed_at TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ,

    CONSTRAINT ck_newsletter_status CHECK (status IN ('PENDING', 'CONFIRMED', 'UNSUBSCRIBED'))
);

CREATE UNIQUE INDEX uq_newsletter_email ON newsletter_subscriptions (lower(email));

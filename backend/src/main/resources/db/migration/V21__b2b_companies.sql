-- =============================================================================
-- V21 : B2B company accounts, negotiated pricing and quote requests
--
-- A company is deliberately separate from the flat companyName/taxNumber fields
-- already on customers — those stay as free-text snapshot fields (used on guest
-- checkout, where there is no account to link to), while a real Company row is
-- only created when someone explicitly registers one and gets vetted by an admin.
-- New companies start PENDING; the negotiated discount only ever applies once an
-- admin has flipped status to ACTIVE.
-- =============================================================================

CREATE TABLE companies
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(160) NOT NULL,
    tax_number           VARCHAR(64),
    discount_percentage  NUMERIC(5, 2) NOT NULL DEFAULT 0,
    status               VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ,
    created_by           BIGINT,
    updated_by           BIGINT,

    CONSTRAINT ck_company_status CHECK (status IN ('PENDING', 'ACTIVE', 'SUSPENDED')),
    CONSTRAINT ck_company_discount CHECK (discount_percentage BETWEEN 0 AND 100)
);

-- One customer belongs to at most one company; a company can have many members.
CREATE TABLE company_members
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id   BIGINT      NOT NULL REFERENCES companies (id) ON DELETE CASCADE,
    customer_id  BIGINT      NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    role         VARCHAR(16) NOT NULL DEFAULT 'BUYER',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ,
    created_by   BIGINT,
    updated_by   BIGINT,

    CONSTRAINT ck_company_member_role CHECK (role IN ('OWNER', 'BUYER')),
    CONSTRAINT uq_company_member_customer UNIQUE (customer_id)
);

CREATE INDEX idx_company_members_company ON company_members (company_id);

-- A sibling of promo_discount, applied on top of it: an approved company's negotiated
-- rate is a separate line from any voucher the buyer also happened to use.
ALTER TABLE orders ADD COLUMN corporate_discount_amount NUMERIC(14, 2) NOT NULL DEFAULT 0;

-- ---- Quote requests (RFQ) ---------------------------------------------------

CREATE TABLE quote_requests
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    BIGINT REFERENCES customers (id) ON DELETE SET NULL,
    company_id     BIGINT REFERENCES companies (id) ON DELETE SET NULL,
    contact_name   VARCHAR(160) NOT NULL,
    contact_email  VARCHAR(190) NOT NULL,
    contact_phone  VARCHAR(40),
    note           VARCHAR(2000),
    status         VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    admin_note     VARCHAR(2000),
    valid_until    TIMESTAMPTZ,
    quoted_total   NUMERIC(14, 2),
    currency       VARCHAR(8)   NOT NULL DEFAULT 'AZN',
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ,
    created_by     BIGINT,
    updated_by     BIGINT,

    CONSTRAINT ck_quote_status CHECK (status IN ('PENDING', 'QUOTED', 'ACCEPTED', 'DECLINED', 'EXPIRED'))
);

CREATE INDEX idx_quote_requests_customer ON quote_requests (customer_id);
CREATE INDEX idx_quote_requests_status ON quote_requests (status);

-- product_name is a snapshot, same reasoning as order_items: a later rename or
-- deletion of the product must never change what a quote said at the time.
CREATE TABLE quote_request_items
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_request_id   BIGINT       NOT NULL REFERENCES quote_requests (id) ON DELETE CASCADE,
    product_id         BIGINT REFERENCES products (id) ON DELETE SET NULL,
    product_name       VARCHAR(200) NOT NULL,
    quantity           INTEGER      NOT NULL,
    quoted_unit_price  NUMERIC(14, 2),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ,
    created_by         BIGINT,
    updated_by         BIGINT,

    CONSTRAINT ck_quote_item_quantity CHECK (quantity > 0)
);

CREATE INDEX idx_quote_items_request ON quote_request_items (quote_request_id);

-- =============================================================================
-- V17 : Back-in-stock notifications
--
-- Just an e-mail against a product — no account required, so a guest browsing an
-- out-of-stock item can still ask to be told when it returns. `notified_at` doubles
-- as the "already handled" marker: once set, the row is inert and is never mailed
-- again for the same restock.
-- =============================================================================

CREATE TABLE stock_notifications
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT       NOT NULL,
    email       VARCHAR(190) NOT NULL,
    notified_at TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_stock_notif_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT uq_stock_notif UNIQUE (product_id, email)
);

CREATE INDEX idx_stock_notif_pending ON stock_notifications (product_id) WHERE notified_at IS NULL;

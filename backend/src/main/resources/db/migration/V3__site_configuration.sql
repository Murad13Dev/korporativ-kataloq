-- =============================================================================
-- V3 : Versioned site configuration (company, branding, theme, feature flags)
--
-- The whole configuration lives in one JSONB document per version. This is system
-- configuration rather than business data, which is what makes draft / preview /
-- publish / rollback cheap: publishing is a status flip, not a 40-column diff.
-- =============================================================================

CREATE TABLE site_configuration_versions
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_number INTEGER     NOT NULL,
    status         VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    label          VARCHAR(160),
    configuration  JSONB       NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ,
    created_by     BIGINT,
    updated_by     BIGINT,
    published_at   TIMESTAMPTZ,
    published_by   BIGINT,

    CONSTRAINT ck_site_config_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    CONSTRAINT uq_site_config_version UNIQUE (version_number),
    CONSTRAINT fk_site_config_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_site_config_publisher FOREIGN KEY (published_by) REFERENCES users (id) ON DELETE SET NULL
);

-- At most one PUBLISHED and one DRAFT version can exist at any time. Enforcing this
-- in the database means a race between two admins cannot produce two live configs.
CREATE UNIQUE INDEX uq_site_config_single_published
    ON site_configuration_versions ((status)) WHERE status = 'PUBLISHED';
CREATE UNIQUE INDEX uq_site_config_single_draft
    ON site_configuration_versions ((status)) WHERE status = 'DRAFT';

CREATE INDEX idx_site_config_created ON site_configuration_versions (created_at DESC);

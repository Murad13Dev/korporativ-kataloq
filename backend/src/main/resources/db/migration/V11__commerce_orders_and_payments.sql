-- =============================================================================
-- V11 : Orders, order lines, status history and payments
--
-- Orders snapshot everything they need (product name, SKU, prices, address). A
-- product being renamed, repriced or deleted must never alter an order already placed.
-- =============================================================================

CREATE TABLE orders
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number   VARCHAR(32)  NOT NULL,
    customer_id    BIGINT,

    -- Contact snapshot (guest checkout has no customer row to read back from).
    customer_name  VARCHAR(160) NOT NULL,
    customer_email VARCHAR(190) NOT NULL,
    customer_phone VARCHAR(40),
    company_name   VARCHAR(160),

    -- Shipping address snapshot
    shipping_country      VARCHAR(80),
    shipping_city         VARCHAR(120),
    shipping_district     VARCHAR(120),
    shipping_address_line TEXT,
    shipping_postal_code  VARCHAR(24),
    shipping_notes        VARCHAR(500),

    status         VARCHAR(24)  NOT NULL DEFAULT 'PENDING',
    payment_status VARCHAR(24)  NOT NULL DEFAULT 'PENDING',
    payment_method VARCHAR(32)  NOT NULL DEFAULT 'ONLINE',
    delivery_method VARCHAR(32) NOT NULL DEFAULT 'COURIER',

    -- Money. `discount_total` is the sum of per-item campaign savings,
    -- `promo_discount` is the cart-level promo code saving. Kept apart so the
    -- customer and the admin can both see where each manat went.
    subtotal        NUMERIC(14, 2) NOT NULL DEFAULT 0,
    discount_total  NUMERIC(14, 2) NOT NULL DEFAULT 0,
    promo_discount  NUMERIC(14, 2) NOT NULL DEFAULT 0,
    promo_code      VARCHAR(48),
    delivery_price  NUMERIC(14, 2) NOT NULL DEFAULT 0,
    tax_total       NUMERIC(14, 2) NOT NULL DEFAULT 0,
    total           NUMERIC(14, 2) NOT NULL DEFAULT 0,
    currency        VARCHAR(8)   NOT NULL DEFAULT 'AZN',

    customer_note   VARCHAR(1000),
    admin_note      TEXT,
    locale          VARCHAR(8)   NOT NULL DEFAULT 'az',
    ip_address      VARCHAR(64),

    placed_at       TIMESTAMPTZ,
    paid_at         TIMESTAMPTZ,
    shipped_at      TIMESTAMPTZ,
    delivered_at    TIMESTAMPTZ,
    cancelled_at    TIMESTAMPTZ,
    cancel_reason   VARCHAR(500),
    -- Payment must complete before this instant or the order is auto-expired.
    payment_expires_at TIMESTAMPTZ,

    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ,
    created_by      BIGINT,
    updated_by      BIGINT,

    CONSTRAINT uq_orders_number UNIQUE (order_number),
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE SET NULL,
    CONSTRAINT ck_orders_status CHECK (status IN
        ('PENDING', 'AWAITING_PAYMENT', 'CONFIRMED', 'PROCESSING', 'SHIPPED', 'DELIVERED', 'COMPLETED', 'CANCELLED', 'REFUNDED', 'EXPIRED')),
    CONSTRAINT ck_orders_payment_status CHECK (payment_status IN
        ('PENDING', 'AUTHORIZED', 'PAID', 'PARTIALLY_REFUNDED', 'REFUNDED', 'FAILED', 'CANCELLED')),
    CONSTRAINT ck_orders_payment_method CHECK (payment_method IN ('ONLINE', 'CASH_ON_DELIVERY', 'BANK_TRANSFER')),
    CONSTRAINT ck_orders_delivery_method CHECK (delivery_method IN ('COURIER', 'PICKUP', 'CARGO')),
    CONSTRAINT ck_orders_totals CHECK (total >= 0 AND subtotal >= 0)
);

CREATE INDEX idx_orders_customer ON orders (customer_id, created_at DESC);
CREATE INDEX idx_orders_status ON orders (status, created_at DESC);
CREATE INDEX idx_orders_payment_status ON orders (payment_status, created_at DESC);
CREATE INDEX idx_orders_email ON orders (lower(customer_email));
CREATE INDEX idx_orders_created ON orders (created_at DESC);
CREATE INDEX idx_orders_payment_expiry ON orders (payment_expires_at)
    WHERE status = 'AWAITING_PAYMENT';


CREATE TABLE order_items
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT       NOT NULL,
    -- Nullable: the product may be deleted later; the snapshot below keeps the line intact.
    product_id      BIGINT,
    product_name    VARCHAR(255) NOT NULL,
    product_sku     VARCHAR(80),
    product_slug    VARCHAR(180),
    image_url       VARCHAR(700),
    quantity        INTEGER      NOT NULL,
    -- List price before any campaign.
    original_unit_price NUMERIC(14, 2) NOT NULL,
    -- Price actually charged per unit.
    unit_price      NUMERIC(14, 2) NOT NULL,
    discount_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    discount_name   VARCHAR(160),
    tax_rate        NUMERIC(5, 2)  NOT NULL DEFAULT 0,
    total_price     NUMERIC(14, 2) NOT NULL,

    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE SET NULL,
    CONSTRAINT ck_order_items_qty CHECK (quantity > 0)
);

CREATE INDEX idx_order_items_order ON order_items (order_id);
CREATE INDEX idx_order_items_product ON order_items (product_id);


CREATE TABLE order_status_history
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT      NOT NULL,
    from_status VARCHAR(24),
    to_status   VARCHAR(24) NOT NULL,
    note        VARCHAR(500),
    changed_by  BIGINT,
    actor_type  VARCHAR(16) NOT NULL DEFAULT 'ADMIN',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_order_history_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT ck_order_history_actor CHECK (actor_type IN ('ADMIN', 'CUSTOMER', 'SYSTEM', 'PAYMENT_PROVIDER'))
);

CREATE INDEX idx_order_history_order ON order_status_history (order_id, created_at DESC);


CREATE TABLE payments
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                BIGINT       NOT NULL,
    provider                VARCHAR(32)  NOT NULL,
    -- Our own reference sent to the provider; also the idempotency key for retries.
    reference               VARCHAR(64)  NOT NULL,
    external_transaction_id VARCHAR(190),
    amount                  NUMERIC(14, 2) NOT NULL,
    refunded_amount         NUMERIC(14, 2) NOT NULL DEFAULT 0,
    currency                VARCHAR(8)   NOT NULL DEFAULT 'AZN',
    status                  VARCHAR(24)  NOT NULL DEFAULT 'CREATED',
    payment_url             VARCHAR(1000),
    card_mask               VARCHAR(32),
    card_brand              VARCHAR(32),
    failure_code            VARCHAR(64),
    failure_message         VARCHAR(500),
    request_payload         JSONB,
    response_payload        JSONB,
    callback_payload        JSONB,
    completed_at            TIMESTAMPTZ,
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ,
    created_by              BIGINT,
    updated_by              BIGINT,

    CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT uq_payments_reference UNIQUE (reference),
    CONSTRAINT ck_payments_status CHECK (status IN
        ('CREATED', 'PENDING', 'AUTHORIZED', 'SUCCEEDED', 'FAILED', 'CANCELLED', 'REFUNDED', 'PARTIALLY_REFUNDED', 'EXPIRED')),
    CONSTRAINT ck_payments_amount CHECK (amount > 0),
    CONSTRAINT ck_payments_refund CHECK (refunded_amount >= 0 AND refunded_amount <= amount)
);

CREATE INDEX idx_payments_order ON payments (order_id);
CREATE INDEX idx_payments_status ON payments (status, created_at DESC);
CREATE INDEX idx_payments_external ON payments (external_transaction_id);


-- Raw provider callbacks, stored before processing. Gives an audit trail and makes
-- duplicate webhook deliveries a no-op instead of a double state transition.
CREATE TABLE payment_events
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id     BIGINT,
    provider       VARCHAR(32)  NOT NULL,
    event_type     VARCHAR(64)  NOT NULL,
    -- Provider-supplied unique id; the unique index makes replays idempotent.
    external_event_id VARCHAR(190),
    payload        JSONB        NOT NULL,
    signature_valid BOOLEAN     NOT NULL DEFAULT FALSE,
    processed      BOOLEAN      NOT NULL DEFAULT FALSE,
    processed_at   TIMESTAMPTZ,
    error_message  VARCHAR(1000),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_payment_events_payment FOREIGN KEY (payment_id) REFERENCES payments (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX uq_payment_events_external
    ON payment_events (provider, external_event_id) WHERE external_event_id IS NOT NULL;
CREATE INDEX idx_payment_events_unprocessed ON payment_events (created_at) WHERE NOT processed;


ALTER TABLE promo_code_redemptions
    ADD CONSTRAINT fk_promo_redemption_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE SET NULL;
ALTER TABLE promo_code_redemptions
    ADD CONSTRAINT fk_promo_redemption_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE SET NULL;


-- Human readable, monotonically increasing order numbers (ORD-2026-000001).
CREATE SEQUENCE order_number_seq START WITH 1 INCREMENT BY 1;

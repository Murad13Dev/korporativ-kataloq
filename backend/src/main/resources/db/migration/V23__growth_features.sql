-- =============================================================================
-- V23 : Referral program + price-drop watch
--
-- Referral: two columns on customers rather than a separate "referrals" table — a
-- referral is a one-time fact about how a customer arrived, not a relationship with its
-- own lifecycle. `referral_rewarded_at` doubles as the "already paid out" guard, exactly
-- like `stock_notifications.notified_at` does for restock mail.
--
-- Price watch: a straight copy of the stock_notifications shape (see V17) — same
-- guest-friendly, e-mail-only, "notify once" design, just keyed to a discount starting
-- instead of stock returning.
-- =============================================================================

ALTER TABLE customers
    ADD COLUMN referral_code VARCHAR(16),
    ADD COLUMN referred_by_customer_id BIGINT,
    ADD COLUMN referral_rewarded_at TIMESTAMPTZ;

ALTER TABLE customers
    ADD CONSTRAINT fk_customers_referred_by FOREIGN KEY (referred_by_customer_id)
        REFERENCES customers (id) ON DELETE SET NULL;

-- Partial: only rows that have a code need to be unique, and legacy customers created
-- before this migration simply have none until they next touch the referral flow.
CREATE UNIQUE INDEX uq_customers_referral_code ON customers (referral_code) WHERE referral_code IS NOT NULL;


CREATE TABLE price_watches
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT       NOT NULL,
    email       VARCHAR(190) NOT NULL,
    notified_at TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_price_watch_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT uq_price_watch UNIQUE (product_id, email)
);

CREATE INDEX idx_price_watch_pending ON price_watches (product_id) WHERE notified_at IS NULL;

-- =============================================================================
-- V2 : Languages and the media library
-- =============================================================================

CREATE TABLE languages
(
    code        VARCHAR(8)  PRIMARY KEY,
    name        VARCHAR(64) NOT NULL,
    native_name VARCHAR(64),
    flag_code   VARCHAR(8),
    is_default  BOOLEAN     NOT NULL DEFAULT FALSE,
    is_active   BOOLEAN     NOT NULL DEFAULT TRUE,
    sort_order  INTEGER     NOT NULL DEFAULT 0
);

-- Exactly one default language may exist.
CREATE UNIQUE INDEX uq_languages_single_default ON languages ((is_default)) WHERE is_default;


CREATE TABLE media_files
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_name VARCHAR(255) NOT NULL,
    stored_name   VARCHAR(255) NOT NULL,
    storage_path  VARCHAR(500) NOT NULL,
    public_url    VARCHAR(700) NOT NULL,
    mime_type     VARCHAR(120) NOT NULL,
    file_size     BIGINT       NOT NULL,
    media_type    VARCHAR(24)  NOT NULL DEFAULT 'IMAGE',
    width         INTEGER,
    height        INTEGER,
    alt_text      VARCHAR(255),
    title         VARCHAR(255),
    folder        VARCHAR(120) NOT NULL DEFAULT 'general',
    checksum      VARCHAR(64),
    uploaded_by   BIGINT,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ,
    created_by    BIGINT,
    updated_by    BIGINT,

    CONSTRAINT fk_media_uploader FOREIGN KEY (uploaded_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_media_stored_name UNIQUE (stored_name),
    CONSTRAINT ck_media_type CHECK (media_type IN ('IMAGE', 'DOCUMENT', 'VIDEO', 'OTHER'))
);

CREATE INDEX idx_media_files_created ON media_files (created_at DESC);
CREATE INDEX idx_media_files_type ON media_files (media_type, created_at DESC);
CREATE INDEX idx_media_files_folder ON media_files (folder);
CREATE INDEX idx_media_files_checksum ON media_files (checksum);

ALTER TABLE users
    ADD CONSTRAINT fk_users_avatar FOREIGN KEY (avatar_media_id) REFERENCES media_files (id) ON DELETE SET NULL;

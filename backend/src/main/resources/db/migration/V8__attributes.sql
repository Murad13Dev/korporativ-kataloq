-- =============================================================================
-- V8 : Product attributes (specifications) and their values
--
-- Values are stored in typed columns rather than a single text column, so
-- NUMBER attributes can be range-filtered and BOOLEAN ones stay queryable.
-- MULTI_SELECT stores one row per selected option — never a JSON array.
-- =============================================================================

CREATE TABLE attribute_groups
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(64) NOT NULL,
    sort_order INTEGER     NOT NULL DEFAULT 0,

    CONSTRAINT uq_attribute_groups_code UNIQUE (code)
);

CREATE TABLE attribute_group_translations
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attribute_group_id BIGINT       NOT NULL,
    language_code      VARCHAR(8)   NOT NULL,
    name               VARCHAR(160) NOT NULL,

    CONSTRAINT fk_attr_group_tr_group FOREIGN KEY (attribute_group_id) REFERENCES attribute_groups (id) ON DELETE CASCADE,
    CONSTRAINT fk_attr_group_tr_lang FOREIGN KEY (language_code) REFERENCES languages (code) ON DELETE CASCADE,
    CONSTRAINT uq_attr_group_tr UNIQUE (attribute_group_id, language_code)
);


CREATE TABLE attributes
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attribute_group_id BIGINT,
    code               VARCHAR(64) NOT NULL,
    data_type          VARCHAR(24) NOT NULL,
    unit               VARCHAR(24),
    -- Exposed as a facet in the public catalog filter panel.
    filterable         BOOLEAN     NOT NULL DEFAULT FALSE,
    -- Rendered in the product card / comparison table, not just the spec sheet.
    show_in_listing    BOOLEAN     NOT NULL DEFAULT FALSE,
    required           BOOLEAN     NOT NULL DEFAULT FALSE,
    status             VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    sort_order         INTEGER     NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ,
    created_by         BIGINT,
    updated_by         BIGINT,

    CONSTRAINT fk_attributes_group FOREIGN KEY (attribute_group_id) REFERENCES attribute_groups (id) ON DELETE SET NULL,
    CONSTRAINT uq_attributes_code UNIQUE (code),
    CONSTRAINT ck_attributes_data_type CHECK (data_type IN ('TEXT', 'NUMBER', 'BOOLEAN', 'SELECT', 'MULTI_SELECT')),
    CONSTRAINT ck_attributes_status CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED'))
);

CREATE INDEX idx_attributes_filterable ON attributes (filterable) WHERE status = 'ACTIVE' AND filterable;


CREATE TABLE attribute_translations
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attribute_id  BIGINT       NOT NULL,
    language_code VARCHAR(8)   NOT NULL,
    name          VARCHAR(160) NOT NULL,
    description   VARCHAR(500),

    CONSTRAINT fk_attribute_tr_attribute FOREIGN KEY (attribute_id) REFERENCES attributes (id) ON DELETE CASCADE,
    CONSTRAINT fk_attribute_tr_lang FOREIGN KEY (language_code) REFERENCES languages (code) ON DELETE CASCADE,
    CONSTRAINT uq_attribute_tr UNIQUE (attribute_id, language_code)
);


CREATE TABLE attribute_options
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attribute_id BIGINT       NOT NULL,
    value        VARCHAR(160) NOT NULL,
    -- Optional swatch for colour-like attributes rendered as chips in the filter.
    color_hex    VARCHAR(16),
    sort_order   INTEGER      NOT NULL DEFAULT 0,

    CONSTRAINT fk_attribute_options_attribute FOREIGN KEY (attribute_id) REFERENCES attributes (id) ON DELETE CASCADE,
    CONSTRAINT uq_attribute_options_value UNIQUE (attribute_id, value)
);

CREATE INDEX idx_attribute_options_attribute ON attribute_options (attribute_id, sort_order);


CREATE TABLE attribute_option_translations
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    option_id     BIGINT       NOT NULL,
    language_code VARCHAR(8)   NOT NULL,
    label         VARCHAR(160) NOT NULL,

    CONSTRAINT fk_attr_option_tr_option FOREIGN KEY (option_id) REFERENCES attribute_options (id) ON DELETE CASCADE,
    CONSTRAINT fk_attr_option_tr_lang FOREIGN KEY (language_code) REFERENCES languages (code) ON DELETE CASCADE,
    CONSTRAINT uq_attr_option_tr UNIQUE (option_id, language_code)
);


CREATE TABLE product_attribute_values
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    BIGINT NOT NULL,
    attribute_id  BIGINT NOT NULL,
    option_id     BIGINT,
    text_value    TEXT,
    number_value  NUMERIC(18, 4),
    boolean_value BOOLEAN,
    sort_order    INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT fk_pav_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT fk_pav_attribute FOREIGN KEY (attribute_id) REFERENCES attributes (id) ON DELETE CASCADE,
    CONSTRAINT fk_pav_option FOREIGN KEY (option_id) REFERENCES attribute_options (id) ON DELETE CASCADE,

    -- Exactly one typed column may be populated, matching the attribute's data type.
    CONSTRAINT ck_pav_single_value CHECK (
        (CASE WHEN option_id IS NOT NULL THEN 1 ELSE 0 END) +
        (CASE WHEN text_value IS NOT NULL THEN 1 ELSE 0 END) +
        (CASE WHEN number_value IS NOT NULL THEN 1 ELSE 0 END) +
        (CASE WHEN boolean_value IS NOT NULL THEN 1 ELSE 0 END) = 1
        )
);

-- A single-valued attribute appears once per product; MULTI_SELECT repeats with
-- distinct option ids, which this index still permits.
CREATE UNIQUE INDEX uq_pav_product_attribute_option
    ON product_attribute_values (product_id, attribute_id, coalesce(option_id, -1));
CREATE INDEX idx_pav_product ON product_attribute_values (product_id);
CREATE INDEX idx_pav_attribute_option ON product_attribute_values (attribute_id, option_id);
CREATE INDEX idx_pav_attribute_number ON product_attribute_values (attribute_id, number_value)
    WHERE number_value IS NOT NULL;

-- Password reset tokens for storefront customers. Mirrors password_reset_tokens (V1),
-- kept as a separate table because it points at customers, not the admin users table —
-- the two audiences must never be able to reset each other's credentials through a
-- shared token pool.
CREATE TABLE customer_password_reset_tokens
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT       NOT NULL,
    token_hash  VARCHAR(128) NOT NULL,
    expires_at  TIMESTAMPTZ  NOT NULL,
    used_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_customer_password_reset_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE,
    CONSTRAINT uq_customer_password_reset_hash UNIQUE (token_hash)
);

CREATE INDEX idx_customer_password_reset_customer ON customer_password_reset_tokens (customer_id) WHERE used_at IS NULL;

-- =============================================================================
-- V10 : Storefront customers, addresses and carts
--
-- Customers are a separate identity domain from admin `users`: different login
-- endpoint, different token audience, no access to /api/admin.
-- =============================================================================

CREATE TABLE customers
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name     VARCHAR(80)  NOT NULL,
    last_name      VARCHAR(80)  NOT NULL,
    email          VARCHAR(190) NOT NULL,
    phone          VARCHAR(40),
    -- NULL for guest records created during guest checkout.
    password_hash  VARCHAR(255),
    company_name   VARCHAR(160),
    tax_number     VARCHAR(64),
    customer_type  VARCHAR(16)  NOT NULL DEFAULT 'INDIVIDUAL',
    status         VARCHAR(24)  NOT NULL DEFAULT 'ACTIVE',
    locale         VARCHAR(8)   NOT NULL DEFAULT 'az',
    email_verified BOOLEAN      NOT NULL DEFAULT FALSE,
    marketing_opt_in BOOLEAN    NOT NULL DEFAULT FALSE,
    last_login_at  TIMESTAMPTZ,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ,
    created_by     BIGINT,
    updated_by     BIGINT,
    deleted_at     TIMESTAMPTZ,

    CONSTRAINT ck_customers_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'BLOCKED', 'GUEST')),
    CONSTRAINT ck_customers_type CHECK (customer_type IN ('INDIVIDUAL', 'COMPANY'))
);

CREATE UNIQUE INDEX uq_customers_email_alive ON customers (lower(email)) WHERE deleted_at IS NULL;
CREATE INDEX idx_customers_status ON customers (status) WHERE deleted_at IS NULL;
CREATE INDEX idx_customers_created ON customers (created_at DESC);


CREATE TABLE customer_refresh_tokens
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT       NOT NULL,
    token_hash  VARCHAR(128) NOT NULL,
    user_agent  VARCHAR(255),
    ip_address  VARCHAR(64),
    expires_at  TIMESTAMPTZ  NOT NULL,
    revoked_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_cust_refresh_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE,
    CONSTRAINT uq_cust_refresh_hash UNIQUE (token_hash)
);

CREATE INDEX idx_cust_refresh_customer ON customer_refresh_tokens (customer_id) WHERE revoked_at IS NULL;


CREATE TABLE addresses
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  BIGINT       NOT NULL,
    title        VARCHAR(80)  NOT NULL DEFAULT 'Ev',
    full_name    VARCHAR(160),
    phone        VARCHAR(40),
    country      VARCHAR(80)  NOT NULL DEFAULT 'Azərbaycan',
    city         VARCHAR(120) NOT NULL,
    district     VARCHAR(120),
    address_line TEXT         NOT NULL,
    postal_code  VARCHAR(24),
    notes        VARCHAR(500),
    is_default   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ,
    created_by   BIGINT,
    updated_by   BIGINT,

    CONSTRAINT fk_addresses_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE
);

CREATE INDEX idx_addresses_customer ON addresses (customer_id);
CREATE UNIQUE INDEX uq_addresses_single_default ON addresses (customer_id) WHERE is_default;


CREATE TABLE carts
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    BIGINT,
    -- Anonymous carts are keyed by a client-generated token kept in localStorage;
    -- on login the guest cart is merged into the customer's cart.
    session_id     VARCHAR(64),
    status         VARCHAR(24)  NOT NULL DEFAULT 'ACTIVE',
    currency       VARCHAR(8)   NOT NULL DEFAULT 'AZN',
    promo_code_id  BIGINT,
    promo_code     VARCHAR(48),
    notes          VARCHAR(1000),
    expires_at     TIMESTAMPTZ,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ,
    created_by     BIGINT,
    updated_by     BIGINT,

    CONSTRAINT fk_carts_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE,
    CONSTRAINT fk_carts_promo FOREIGN KEY (promo_code_id) REFERENCES promo_codes (id) ON DELETE SET NULL,
    CONSTRAINT ck_carts_status CHECK (status IN ('ACTIVE', 'CONVERTED', 'ABANDONED')),
    CONSTRAINT ck_carts_owner CHECK (customer_id IS NOT NULL OR session_id IS NOT NULL)
);

CREATE UNIQUE INDEX uq_carts_active_customer ON carts (customer_id) WHERE status = 'ACTIVE' AND customer_id IS NOT NULL;
CREATE UNIQUE INDEX uq_carts_active_session ON carts (session_id) WHERE status = 'ACTIVE' AND session_id IS NOT NULL;
CREATE INDEX idx_carts_updated ON carts (updated_at);


CREATE TABLE cart_items
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id     BIGINT  NOT NULL,
    product_id  BIGINT  NOT NULL,
    quantity    INTEGER NOT NULL DEFAULT 1,
    -- Price snapshot taken when the line was added. Re-validated at checkout so the
    -- customer is told explicitly if a campaign started or ended in the meantime.
    unit_price  NUMERIC(14, 2) NOT NULL,
    original_unit_price NUMERIC(14, 2) NOT NULL,
    discount_id BIGINT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ,
    created_by  BIGINT,
    updated_by  BIGINT,

    CONSTRAINT fk_cart_items_cart FOREIGN KEY (cart_id) REFERENCES carts (id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_items_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_items_discount FOREIGN KEY (discount_id) REFERENCES discounts (id) ON DELETE SET NULL,
    CONSTRAINT uq_cart_items UNIQUE (cart_id, product_id),
    CONSTRAINT ck_cart_items_qty CHECK (quantity > 0)
);

CREATE INDEX idx_cart_items_cart ON cart_items (cart_id);


-- Saved-for-later / wishlist, shared by the cart drawer and the account area.
CREATE TABLE wishlist_items
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT      NOT NULL,
    product_id  BIGINT      NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_wishlist_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE,
    CONSTRAINT fk_wishlist_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT uq_wishlist UNIQUE (customer_id, product_id)
);

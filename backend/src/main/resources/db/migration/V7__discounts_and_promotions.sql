-- =============================================================================
-- V7 : Discount campaigns and cart-level promo codes
--
-- A discount is a *campaign*, not a column on the product. That is what makes
-- "20% off all furniture between Friday and Monday" a single row an admin can
-- schedule, pause and roll back without touching a single product record.
--
-- Resolution rule (implemented in DiscountResolver): among all campaigns that are
-- ACTIVE, in their date window and match the product, the highest `priority` wins;
-- ties are broken by the largest customer saving. Campaigns never stack.
-- =============================================================================

CREATE TABLE discounts
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(160) NOT NULL,
    description         VARCHAR(500),

    discount_type       VARCHAR(24)  NOT NULL,
    value               NUMERIC(14, 2) NOT NULL,
    -- Ceiling for percentage campaigns, e.g. "30% off, max 50 AZN".
    max_discount_amount NUMERIC(14, 2),

    scope               VARCHAR(24)  NOT NULL DEFAULT 'PRODUCTS',

    starts_at           TIMESTAMPTZ,
    ends_at             TIMESTAMPTZ,

    -- Higher wins when several campaigns match the same product.
    priority            INTEGER      NOT NULL DEFAULT 0,

    -- ---- storefront ribbon presentation ----------------------------------
    show_badge          BOOLEAN      NOT NULL DEFAULT TRUE,
    -- NULL renders the automatic label ("-25%" / "-15 ₼"); set it to override
    -- with campaign wording such as "BLACK FRIDAY".
    badge_label         VARCHAR(48),
    badge_style         VARCHAR(24)  NOT NULL DEFAULT 'SALE',
    -- Optional explicit ribbon colour; falls back to the theme's sale colour.
    badge_color         VARCHAR(16),
    show_countdown      BOOLEAN      NOT NULL DEFAULT FALSE,

    status              VARCHAR(16)  NOT NULL DEFAULT 'DRAFT',
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ,
    created_by          BIGINT,
    updated_by          BIGINT,
    deleted_at          TIMESTAMPTZ,

    CONSTRAINT ck_discounts_type CHECK (discount_type IN ('PERCENTAGE', 'FIXED_AMOUNT')),
    CONSTRAINT ck_discounts_scope CHECK (scope IN ('ALL_PRODUCTS', 'CATEGORIES', 'PRODUCTS')),
    CONSTRAINT ck_discounts_status CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED')),
    CONSTRAINT ck_discounts_badge_style CHECK (badge_style IN ('SALE', 'HOT', 'SEASONAL', 'CLEARANCE', 'BUNDLE', 'CUSTOM')),
    CONSTRAINT ck_discounts_value CHECK (value > 0),
    CONSTRAINT ck_discounts_percentage_range CHECK (discount_type <> 'PERCENTAGE' OR value <= 100),
    CONSTRAINT ck_discounts_window CHECK (starts_at IS NULL OR ends_at IS NULL OR ends_at > starts_at)
);

CREATE INDEX idx_discounts_active_window ON discounts (status, starts_at, ends_at) WHERE deleted_at IS NULL;
CREATE INDEX idx_discounts_scope ON discounts (scope) WHERE deleted_at IS NULL AND status = 'ACTIVE';


CREATE TABLE discount_products
(
    discount_id BIGINT NOT NULL,
    product_id  BIGINT NOT NULL,

    PRIMARY KEY (discount_id, product_id),
    CONSTRAINT fk_discount_products_discount FOREIGN KEY (discount_id) REFERENCES discounts (id) ON DELETE CASCADE,
    CONSTRAINT fk_discount_products_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE
);

CREATE INDEX idx_discount_products_product ON discount_products (product_id);


CREATE TABLE discount_categories
(
    discount_id BIGINT  NOT NULL,
    category_id BIGINT  NOT NULL,
    -- When true the campaign also applies to every descendant category.
    include_descendants BOOLEAN NOT NULL DEFAULT TRUE,

    PRIMARY KEY (discount_id, category_id),
    CONSTRAINT fk_discount_categories_discount FOREIGN KEY (discount_id) REFERENCES discounts (id) ON DELETE CASCADE,
    CONSTRAINT fk_discount_categories_category FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE CASCADE
);

CREATE INDEX idx_discount_categories_category ON discount_categories (category_id);


-- =============================================================================
-- Cart level promo codes — applied by the customer at checkout, independent of
-- product campaigns (a cart can carry both: item discounts + one promo code).
-- =============================================================================

CREATE TABLE promo_codes
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(48)  NOT NULL,
    description         VARCHAR(500),

    discount_type       VARCHAR(24)  NOT NULL,
    value               NUMERIC(14, 2) NOT NULL,
    max_discount_amount NUMERIC(14, 2),
    min_subtotal        NUMERIC(14, 2) NOT NULL DEFAULT 0,
    -- FREE_DELIVERY codes zero the delivery fee instead of the subtotal.
    free_delivery       BOOLEAN      NOT NULL DEFAULT FALSE,

    starts_at           TIMESTAMPTZ,
    ends_at             TIMESTAMPTZ,

    usage_limit         INTEGER,
    usage_limit_per_customer INTEGER NOT NULL DEFAULT 1,
    used_count          INTEGER      NOT NULL DEFAULT 0,

    -- When true the code cannot be combined with products already on campaign.
    exclude_discounted  BOOLEAN      NOT NULL DEFAULT FALSE,

    status              VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ,
    created_by          BIGINT,
    updated_by          BIGINT,
    deleted_at          TIMESTAMPTZ,

    CONSTRAINT ck_promo_type CHECK (discount_type IN ('PERCENTAGE', 'FIXED_AMOUNT')),
    CONSTRAINT ck_promo_status CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED')),
    CONSTRAINT ck_promo_value CHECK (value >= 0),
    CONSTRAINT ck_promo_percentage_range CHECK (discount_type <> 'PERCENTAGE' OR value <= 100),
    CONSTRAINT ck_promo_window CHECK (starts_at IS NULL OR ends_at IS NULL OR ends_at > starts_at)
);

CREATE UNIQUE INDEX uq_promo_codes_code ON promo_codes (upper(code)) WHERE deleted_at IS NULL;
CREATE INDEX idx_promo_codes_status ON promo_codes (status, starts_at, ends_at) WHERE deleted_at IS NULL;


CREATE TABLE promo_code_redemptions
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    promo_code_id BIGINT      NOT NULL,
    order_id      BIGINT,
    customer_id   BIGINT,
    customer_email VARCHAR(190),
    amount        NUMERIC(14, 2) NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_promo_redemption_code FOREIGN KEY (promo_code_id) REFERENCES promo_codes (id) ON DELETE CASCADE
);

CREATE INDEX idx_promo_redemption_code ON promo_code_redemptions (promo_code_id);
CREATE INDEX idx_promo_redemption_customer ON promo_code_redemptions (customer_id);
CREATE INDEX idx_promo_redemption_email ON promo_code_redemptions (lower(customer_email));

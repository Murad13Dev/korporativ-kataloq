-- =============================================================================
-- V12 : Live chat — conversations and messages
--
-- A conversation can be started by a logged-in customer or by a completely
-- anonymous visitor (identified by a browser-side token), which is why both
-- `customer_id` and `visitor_token` are nullable but at least one is required.
-- =============================================================================

CREATE TABLE conversations
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id       BIGINT,
    visitor_token     VARCHAR(64),
    visitor_name      VARCHAR(160),
    visitor_email     VARCHAR(190),
    visitor_phone     VARCHAR(40),
    subject           VARCHAR(255),
    assigned_admin_id BIGINT,
    order_id          BIGINT,
    product_id        BIGINT,
    status            VARCHAR(24) NOT NULL DEFAULT 'OPEN',
    priority          VARCHAR(16) NOT NULL DEFAULT 'NORMAL',
    locale            VARCHAR(8)  NOT NULL DEFAULT 'az',
    source_url        VARCHAR(500),

    -- Denormalised counters so the admin inbox list needs no per-row subquery.
    last_message_at   TIMESTAMPTZ,
    last_message_preview VARCHAR(255),
    unread_by_admin   INTEGER     NOT NULL DEFAULT 0,
    unread_by_customer INTEGER    NOT NULL DEFAULT 0,

    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ,
    created_by        BIGINT,
    updated_by        BIGINT,
    closed_at         TIMESTAMPTZ,
    closed_by         BIGINT,

    CONSTRAINT fk_conversations_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE SET NULL,
    CONSTRAINT fk_conversations_admin FOREIGN KEY (assigned_admin_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_conversations_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE SET NULL,
    CONSTRAINT fk_conversations_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE SET NULL,
    CONSTRAINT ck_conversations_status CHECK (status IN ('OPEN', 'PENDING', 'RESOLVED', 'CLOSED')),
    CONSTRAINT ck_conversations_priority CHECK (priority IN ('LOW', 'NORMAL', 'HIGH', 'URGENT')),
    CONSTRAINT ck_conversations_participant CHECK (customer_id IS NOT NULL OR visitor_token IS NOT NULL)
);

CREATE INDEX idx_conversations_status ON conversations (status, last_message_at DESC);
CREATE INDEX idx_conversations_admin ON conversations (assigned_admin_id, status);
CREATE INDEX idx_conversations_customer ON conversations (customer_id, created_at DESC);
CREATE INDEX idx_conversations_visitor ON conversations (visitor_token) WHERE visitor_token IS NOT NULL;
CREATE INDEX idx_conversations_unread ON conversations (unread_by_admin) WHERE unread_by_admin > 0;


CREATE TABLE messages
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT      NOT NULL,
    sender_type     VARCHAR(16) NOT NULL,
    -- References users.id for ADMIN, customers.id for CUSTOMER, NULL for SYSTEM/visitors.
    sender_id       BIGINT,
    sender_name     VARCHAR(160),
    message         TEXT,
    message_type    VARCHAR(24) NOT NULL DEFAULT 'TEXT',
    media_id        BIGINT,
    -- Structured payload for PRODUCT / ORDER cards shared inside the thread.
    metadata        JSONB,
    is_read         BOOLEAN     NOT NULL DEFAULT FALSE,
    read_at         TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_messages_conversation FOREIGN KEY (conversation_id) REFERENCES conversations (id) ON DELETE CASCADE,
    CONSTRAINT fk_messages_media FOREIGN KEY (media_id) REFERENCES media_files (id) ON DELETE SET NULL,
    CONSTRAINT ck_messages_sender_type CHECK (sender_type IN ('CUSTOMER', 'ADMIN', 'SYSTEM', 'BOT')),
    CONSTRAINT ck_messages_type CHECK (message_type IN ('TEXT', 'IMAGE', 'FILE', 'PRODUCT', 'ORDER', 'SYSTEM_EVENT')),
    CONSTRAINT ck_messages_body CHECK (message IS NOT NULL OR media_id IS NOT NULL OR metadata IS NOT NULL)
);

CREATE INDEX idx_messages_conversation ON messages (conversation_id, created_at);
CREATE INDEX idx_messages_unread ON messages (conversation_id, sender_type) WHERE NOT is_read;


-- Canned replies the support team can insert with one click.
CREATE TABLE chat_quick_replies
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(64)  NOT NULL,
    title      VARCHAR(160) NOT NULL,
    body       TEXT         NOT NULL,
    language_code VARCHAR(8),
    sort_order INTEGER      NOT NULL DEFAULT 0,
    is_active  BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    created_by BIGINT,
    updated_by BIGINT,

    CONSTRAINT uq_chat_quick_replies_code UNIQUE (code)
);

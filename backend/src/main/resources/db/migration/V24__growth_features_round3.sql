-- "Reminder already sent" guard for cart-abandonment mail — same "notify once" shape
-- as stock_notifications.notified_at (see V17), just living on the cart itself since
-- there is exactly one reminder per cart, not per product.
ALTER TABLE carts ADD COLUMN abandoned_reminder_sent_at TIMESTAMPTZ;

-- Lazily generated the first time a customer asks to share their wishlist — see
-- referral_code (V23) for the identical pattern. NULL until then.
ALTER TABLE customers ADD COLUMN wishlist_share_token VARCHAR(24);
CREATE UNIQUE INDEX uq_customers_wishlist_share_token
    ON customers (wishlist_share_token) WHERE wishlist_share_token IS NOT NULL;

-- One browser/device subscription per row. `endpoint` is unique on its own (it already
-- encodes the push service + a per-subscription id), so re-subscribing the same device
-- is an upsert, not a duplicate row.
CREATE TABLE push_subscriptions
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT       NOT NULL,
    endpoint    VARCHAR(700) NOT NULL,
    p256dh_key  VARCHAR(200) NOT NULL,
    auth_key    VARCHAR(100) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT fk_push_sub_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE,
    CONSTRAINT uq_push_sub_endpoint UNIQUE (endpoint)
);

CREATE INDEX idx_push_sub_customer ON push_subscriptions (customer_id);

-- Exactly one row, ever. Generated on first boot if VAPID_PUBLIC_KEY/VAPID_PRIVATE_KEY
-- are unset (mirrors BootstrapAdminInitializer's generated-password pattern) and then
-- persisted here so a container restart doesn't silently invalidate every browser's
-- push subscription by rotating the keypair out from under them.
CREATE TABLE vapid_keys
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_key  TEXT        NOT NULL,
    private_key TEXT        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

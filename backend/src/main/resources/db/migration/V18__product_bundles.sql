-- =============================================================================
-- V18 : Product bundles ("frequently bought together")
--
-- Deliberately not a pricing feature: a bundle is a curated cross-sell list shown on
-- its anchor product's page, and the combined price is just the sum of the individual
-- item prices already resolved by DiscountResolver — no separate bundle-price field,
-- so nothing here can ever quote a number checkout doesn't also charge.
-- =============================================================================

CREATE TABLE product_bundles
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(160) NOT NULL,
    primary_product_id  BIGINT       NOT NULL,
    active              BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order          INTEGER      NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ,
    created_by          BIGINT,
    updated_by          BIGINT,

    CONSTRAINT fk_bundle_primary_product FOREIGN KEY (primary_product_id) REFERENCES products (id) ON DELETE CASCADE
);

CREATE INDEX idx_bundles_primary_product ON product_bundles (primary_product_id) WHERE active = TRUE;

CREATE TABLE product_bundle_items
(
    bundle_id  BIGINT NOT NULL,
    product_id BIGINT NOT NULL,

    PRIMARY KEY (bundle_id, product_id),
    CONSTRAINT fk_bundle_item_bundle FOREIGN KEY (bundle_id) REFERENCES product_bundles (id) ON DELETE CASCADE,
    CONSTRAINT fk_bundle_item_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE
);

-- =============================================================================
-- V19 : Loyalty points
--
-- A ledger, not a running balance column: every award and redemption is its own row,
-- so the balance (SUM(points)) is always reconstructible and never drifts out of sync
-- with what actually happened. The partial unique index on (order_id) where type is
-- EARNED stops a status bouncing COMPLETED -> REFUNDED -> COMPLETED from awarding twice.
-- =============================================================================

CREATE TABLE loyalty_transactions
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT      NOT NULL,
    points      INTEGER     NOT NULL,
    type        VARCHAR(16) NOT NULL,
    order_id    BIGINT,
    description VARCHAR(255),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_loyalty_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE,
    CONSTRAINT ck_loyalty_type CHECK (type IN ('EARNED', 'REDEEMED'))
);

CREATE INDEX idx_loyalty_customer ON loyalty_transactions (customer_id);
CREATE UNIQUE INDEX uq_loyalty_order_earn ON loyalty_transactions (order_id) WHERE type = 'EARNED';

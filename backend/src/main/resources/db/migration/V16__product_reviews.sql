-- =============================================================================
-- V16 : Product reviews and ratings
--
-- Every review starts PENDING and only counts toward the public rating average
-- once an admin approves it — a storefront with unmoderated reviews is a spam
-- magnet on day one. `verified_purchase` is computed at submission time from the
-- customer's own order history, never taken on trust from the request body.
-- =============================================================================

CREATE TABLE product_reviews
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id         BIGINT       NOT NULL,
    customer_id        BIGINT,
    author_name        VARCHAR(160) NOT NULL,
    rating             INTEGER      NOT NULL,
    title              VARCHAR(200),
    body               TEXT,
    status             VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    verified_purchase  BOOLEAN      NOT NULL DEFAULT FALSE,
    admin_reply        TEXT,
    admin_reply_at     TIMESTAMPTZ,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ,
    created_by         BIGINT,
    updated_by         BIGINT,

    CONSTRAINT fk_review_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT fk_review_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE SET NULL,
    CONSTRAINT ck_review_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_review_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE INDEX idx_reviews_product ON product_reviews (product_id, status);

-- One review per customer per product; anonymous/guest rows (customer_id NULL) are
-- exempt since there is no identity to de-duplicate against.
CREATE UNIQUE INDEX uq_review_customer_product ON product_reviews (product_id, customer_id)
    WHERE customer_id IS NOT NULL;

-- =============================================================================
-- V4 : Versioned navigation menus
-- =============================================================================

CREATE TABLE menus
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(64)  NOT NULL,
    name       VARCHAR(160) NOT NULL,
    location   VARCHAR(32)  NOT NULL,
    is_active  BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    created_by BIGINT,
    updated_by BIGINT,

    CONSTRAINT uq_menus_code UNIQUE (code),
    CONSTRAINT ck_menus_location CHECK (location IN ('HEADER', 'FOOTER_PRIMARY', 'FOOTER_SECONDARY', 'MOBILE', 'LEGAL'))
);

CREATE INDEX idx_menus_location ON menus (location) WHERE is_active;


CREATE TABLE menu_versions
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_id        BIGINT      NOT NULL,
    version_number INTEGER     NOT NULL,
    status         VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ,
    created_by     BIGINT,
    updated_by     BIGINT,
    published_at   TIMESTAMPTZ,

    CONSTRAINT fk_menu_versions_menu FOREIGN KEY (menu_id) REFERENCES menus (id) ON DELETE CASCADE,
    CONSTRAINT uq_menu_versions_number UNIQUE (menu_id, version_number),
    CONSTRAINT ck_menu_versions_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED'))
);

CREATE UNIQUE INDEX uq_menu_versions_single_published
    ON menu_versions (menu_id) WHERE status = 'PUBLISHED';
CREATE UNIQUE INDEX uq_menu_versions_single_draft
    ON menu_versions (menu_id) WHERE status = 'DRAFT';


CREATE TABLE menu_items
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_version_id BIGINT       NOT NULL,
    parent_id       BIGINT,
    title           VARCHAR(160) NOT NULL,
    url             VARCHAR(500) NOT NULL,
    link_type       VARCHAR(24)  NOT NULL DEFAULT 'CUSTOM',
    reference_id    BIGINT,
    icon            VARCHAR(64),
    description     VARCHAR(255),
    target          VARCHAR(16)  NOT NULL DEFAULT '_self',
    highlight       BOOLEAN      NOT NULL DEFAULT FALSE,
    sort_order      INTEGER      NOT NULL DEFAULT 0,
    is_active       BOOLEAN      NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_menu_items_version FOREIGN KEY (menu_version_id) REFERENCES menu_versions (id) ON DELETE CASCADE,
    CONSTRAINT fk_menu_items_parent FOREIGN KEY (parent_id) REFERENCES menu_items (id) ON DELETE CASCADE,
    CONSTRAINT ck_menu_items_target CHECK (target IN ('_self', '_blank')),
    CONSTRAINT ck_menu_items_link_type CHECK (link_type IN ('CUSTOM', 'PAGE', 'CATEGORY', 'PRODUCT', 'POST', 'EXTERNAL'))
);

CREATE INDEX idx_menu_items_version ON menu_items (menu_version_id, sort_order);
CREATE INDEX idx_menu_items_parent ON menu_items (parent_id);


-- Menu item labels are translated per active language.
CREATE TABLE menu_item_translations
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_item_id  BIGINT       NOT NULL,
    language_code VARCHAR(8)   NOT NULL,
    title         VARCHAR(160) NOT NULL,
    description   VARCHAR(255),

    CONSTRAINT fk_menu_item_tr_item FOREIGN KEY (menu_item_id) REFERENCES menu_items (id) ON DELETE CASCADE,
    CONSTRAINT fk_menu_item_tr_lang FOREIGN KEY (language_code) REFERENCES languages (code) ON DELETE CASCADE,
    CONSTRAINT uq_menu_item_tr UNIQUE (menu_item_id, language_code)
);

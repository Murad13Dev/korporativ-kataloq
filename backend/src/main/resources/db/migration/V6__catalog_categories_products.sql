-- =============================================================================
-- V6 : Catalog — categories, products, translations, images, documents
-- =============================================================================

CREATE TABLE categories
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id      BIGINT,
    slug           VARCHAR(180) NOT NULL,
    image_media_id BIGINT,
    icon_media_id  BIGINT,
    banner_media_id BIGINT,
    icon           VARCHAR(64),
    status         VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    featured       BOOLEAN      NOT NULL DEFAULT FALSE,
    show_in_menu   BOOLEAN      NOT NULL DEFAULT TRUE,
    -- Materialised ancestor path ("1/14/57") so descendant queries stay a single
    -- indexed LIKE instead of a recursive walk on every catalog request.
    path           VARCHAR(500) NOT NULL DEFAULT '',
    depth          INTEGER      NOT NULL DEFAULT 0,
    sort_order     INTEGER      NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ,
    created_by     BIGINT,
    updated_by     BIGINT,
    deleted_at     TIMESTAMPTZ,

    CONSTRAINT fk_categories_parent FOREIGN KEY (parent_id) REFERENCES categories (id) ON DELETE RESTRICT,
    CONSTRAINT fk_categories_image FOREIGN KEY (image_media_id) REFERENCES media_files (id) ON DELETE SET NULL,
    CONSTRAINT fk_categories_icon FOREIGN KEY (icon_media_id) REFERENCES media_files (id) ON DELETE SET NULL,
    CONSTRAINT fk_categories_banner FOREIGN KEY (banner_media_id) REFERENCES media_files (id) ON DELETE SET NULL,
    CONSTRAINT ck_categories_status CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED'))
);

CREATE UNIQUE INDEX uq_categories_slug_alive ON categories (slug) WHERE deleted_at IS NULL;
CREATE INDEX idx_categories_parent ON categories (parent_id);
CREATE INDEX idx_categories_path ON categories (path varchar_pattern_ops);
CREATE INDEX idx_categories_status ON categories (status) WHERE deleted_at IS NULL;


CREATE TABLE category_translations
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id     BIGINT       NOT NULL,
    language_code   VARCHAR(8)   NOT NULL,
    name            VARCHAR(255) NOT NULL,
    description     TEXT,
    seo_title       VARCHAR(255),
    seo_description VARCHAR(500),

    CONSTRAINT fk_category_tr_category FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE CASCADE,
    CONSTRAINT fk_category_tr_lang FOREIGN KEY (language_code) REFERENCES languages (code) ON DELETE CASCADE,
    CONSTRAINT uq_category_tr UNIQUE (category_id, language_code)
);

CREATE INDEX idx_category_tr_name ON category_translations (language_code, name);


CREATE TABLE products
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id     BIGINT,
    brand_id        BIGINT,
    sku             VARCHAR(80)  NOT NULL,
    barcode         VARCHAR(80),
    slug            VARCHAR(180) NOT NULL,

    -- Pricing. `price` is always the undiscounted list price; the effective sale price is
    -- derived at read time from the active discount so history is never rewritten.
    price           NUMERIC(14, 2),
    -- Optional manual "was" price used purely for display when no discount rule applies.
    compare_at_price NUMERIC(14, 2),
    cost_price      NUMERIC(14, 2),
    currency        VARCHAR(8)   NOT NULL DEFAULT 'AZN',
    tax_rate        NUMERIC(5, 2) NOT NULL DEFAULT 0,
    show_price      BOOLEAN      NOT NULL DEFAULT TRUE,

    -- Commerce
    purchasable     BOOLEAN      NOT NULL DEFAULT TRUE,
    track_stock     BOOLEAN      NOT NULL DEFAULT FALSE,
    stock_quantity  INTEGER      NOT NULL DEFAULT 0,
    low_stock_threshold INTEGER  NOT NULL DEFAULT 5,
    allow_backorder BOOLEAN      NOT NULL DEFAULT FALSE,
    min_order_quantity INTEGER   NOT NULL DEFAULT 1,
    max_order_quantity INTEGER,
    weight_grams    INTEGER,

    featured        BOOLEAN      NOT NULL DEFAULT FALSE,
    is_new          BOOLEAN      NOT NULL DEFAULT FALSE,
    status          VARCHAR(16)  NOT NULL DEFAULT 'DRAFT',
    sort_order      INTEGER      NOT NULL DEFAULT 0,
    view_count      BIGINT       NOT NULL DEFAULT 0,
    published_at    TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ,
    created_by      BIGINT,
    updated_by      BIGINT,
    deleted_at      TIMESTAMPTZ,

    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE SET NULL,
    CONSTRAINT ck_products_status CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED')),
    CONSTRAINT ck_products_price CHECK (price IS NULL OR price >= 0),
    CONSTRAINT ck_products_stock CHECK (stock_quantity >= 0),
    CONSTRAINT ck_products_min_qty CHECK (min_order_quantity >= 1),
    CONSTRAINT ck_products_max_qty CHECK (max_order_quantity IS NULL OR max_order_quantity >= min_order_quantity)
);

CREATE UNIQUE INDEX uq_products_sku_alive ON products (upper(sku)) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX uq_products_slug_alive ON products (slug) WHERE deleted_at IS NULL;
CREATE INDEX idx_products_status ON products (status) WHERE deleted_at IS NULL;
CREATE INDEX idx_products_category ON products (category_id) WHERE deleted_at IS NULL;
CREATE INDEX idx_products_featured ON products (featured) WHERE deleted_at IS NULL AND featured;
CREATE INDEX idx_products_price ON products (price) WHERE deleted_at IS NULL;
CREATE INDEX idx_products_created ON products (created_at DESC) WHERE deleted_at IS NULL;


CREATE TABLE product_translations
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id        BIGINT       NOT NULL,
    language_code     VARCHAR(8)   NOT NULL,
    name              VARCHAR(255) NOT NULL,
    short_description TEXT,
    description       TEXT,
    seo_title         VARCHAR(255),
    seo_description   VARCHAR(500),

    CONSTRAINT fk_product_tr_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT fk_product_tr_lang FOREIGN KEY (language_code) REFERENCES languages (code) ON DELETE CASCADE,
    CONSTRAINT uq_product_tr UNIQUE (product_id, language_code)
);

CREATE INDEX idx_product_tr_name ON product_translations (language_code, name);

-- Full-text search across name + descriptions, built on PostgreSQL only (no Elasticsearch in v1).
CREATE INDEX idx_product_tr_fts ON product_translations
    USING gin (to_tsvector('simple', coalesce(name, '') || ' ' || coalesce(short_description, '')));


CREATE TABLE product_images
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT  NOT NULL,
    media_id   BIGINT  NOT NULL,
    is_main    BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT fk_product_images_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT fk_product_images_media FOREIGN KEY (media_id) REFERENCES media_files (id) ON DELETE CASCADE,
    CONSTRAINT uq_product_images UNIQUE (product_id, media_id)
);

-- Exactly one main image per product.
CREATE UNIQUE INDEX uq_product_images_single_main ON product_images (product_id) WHERE is_main;
CREATE INDEX idx_product_images_product ON product_images (product_id, sort_order);


CREATE TABLE product_documents
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    BIGINT       NOT NULL,
    media_id      BIGINT       NOT NULL,
    title         VARCHAR(255) NOT NULL,
    document_type VARCHAR(32)  NOT NULL DEFAULT 'DATASHEET',
    sort_order    INTEGER      NOT NULL DEFAULT 0,

    CONSTRAINT fk_product_docs_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT fk_product_docs_media FOREIGN KEY (media_id) REFERENCES media_files (id) ON DELETE CASCADE,
    CONSTRAINT ck_product_docs_type CHECK (document_type IN ('DATASHEET', 'MANUAL', 'CERTIFICATE', 'CATALOG', 'WARRANTY', 'OTHER'))
);

CREATE INDEX idx_product_docs_product ON product_documents (product_id, sort_order);


-- Cross-sell / related products, curated by the admin.
CREATE TABLE product_relations
(
    product_id         BIGINT      NOT NULL,
    related_product_id BIGINT      NOT NULL,
    relation_type      VARCHAR(24) NOT NULL DEFAULT 'RELATED',
    sort_order         INTEGER     NOT NULL DEFAULT 0,

    PRIMARY KEY (product_id, related_product_id, relation_type),
    CONSTRAINT fk_product_rel_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT fk_product_rel_related FOREIGN KEY (related_product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT ck_product_rel_type CHECK (relation_type IN ('RELATED', 'UPSELL', 'CROSS_SELL', 'ACCESSORY')),
    CONSTRAINT ck_product_rel_not_self CHECK (product_id <> related_product_id)
);

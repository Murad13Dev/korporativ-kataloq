-- =============================================================================
-- V5 : Pages, per-language versions and their composable sections
--
-- Sections hang off a PAGE_VERSION rather than off the page, so editing a draft
-- can never disturb what the public site is currently rendering.
-- =============================================================================

CREATE TABLE pages
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64) NOT NULL,
    page_type   VARCHAR(32) NOT NULL DEFAULT 'STANDARD',
    -- System pages (HOME, CONTACT, CATALOG…) can be edited but never deleted.
    is_system   BOOLEAN     NOT NULL DEFAULT FALSE,
    layout      VARCHAR(32) NOT NULL DEFAULT 'DEFAULT',
    sort_order  INTEGER     NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ,
    created_by  BIGINT,
    updated_by  BIGINT,
    deleted_at  TIMESTAMPTZ,

    CONSTRAINT uq_pages_code UNIQUE (code),
    CONSTRAINT ck_pages_type CHECK (page_type IN ('STANDARD', 'HOME', 'CONTACT', 'ABOUT', 'CATALOG', 'BLOG', 'LEGAL', 'LANDING'))
);


CREATE TABLE page_versions
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id           BIGINT       NOT NULL,
    version_number    INTEGER      NOT NULL,
    language_code     VARCHAR(8)   NOT NULL,
    slug              VARCHAR(180) NOT NULL,
    title             VARCHAR(255) NOT NULL,
    short_description VARCHAR(500),
    cover_media_id    BIGINT,
    seo_title         VARCHAR(255),
    seo_description   VARCHAR(500),
    seo_keywords      VARCHAR(500),
    og_media_id       BIGINT,
    canonical_url     VARCHAR(500),
    allow_indexing    BOOLEAN      NOT NULL DEFAULT TRUE,
    status            VARCHAR(16)  NOT NULL DEFAULT 'DRAFT',
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ,
    created_by        BIGINT,
    updated_by        BIGINT,
    published_at      TIMESTAMPTZ,

    CONSTRAINT fk_page_versions_page FOREIGN KEY (page_id) REFERENCES pages (id) ON DELETE CASCADE,
    CONSTRAINT fk_page_versions_lang FOREIGN KEY (language_code) REFERENCES languages (code) ON DELETE CASCADE,
    CONSTRAINT fk_page_versions_cover FOREIGN KEY (cover_media_id) REFERENCES media_files (id) ON DELETE SET NULL,
    CONSTRAINT fk_page_versions_og FOREIGN KEY (og_media_id) REFERENCES media_files (id) ON DELETE SET NULL,
    CONSTRAINT uq_page_versions_number UNIQUE (page_id, language_code, version_number),
    CONSTRAINT ck_page_versions_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED'))
);

CREATE UNIQUE INDEX uq_page_versions_single_published
    ON page_versions (page_id, language_code) WHERE status = 'PUBLISHED';
CREATE UNIQUE INDEX uq_page_versions_single_draft
    ON page_versions (page_id, language_code) WHERE status = 'DRAFT';

-- A slug identifies exactly one live page per language.
CREATE UNIQUE INDEX uq_page_versions_published_slug
    ON page_versions (language_code, slug) WHERE status = 'PUBLISHED';

CREATE INDEX idx_page_versions_lookup ON page_versions (language_code, slug, status);
CREATE INDEX idx_page_versions_page ON page_versions (page_id, language_code, status);


CREATE TABLE page_sections
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_version_id BIGINT      NOT NULL,
    section_type    VARCHAR(48) NOT NULL,
    variant         VARCHAR(32) NOT NULL DEFAULT 'DEFAULT',
    title           VARCHAR(255),
    subtitle        VARCHAR(500),
    eyebrow         VARCHAR(120),
    content         TEXT,
    media_id        BIGINT,
    background_media_id BIGINT,
    button_text     VARCHAR(120),
    button_url      VARCHAR(500),
    secondary_button_text VARCHAR(120),
    secondary_button_url  VARCHAR(500),
    background_style VARCHAR(24) NOT NULL DEFAULT 'DEFAULT',
    -- Section-specific data: cards, stats, slides, filters. Structure is validated per
    -- section_type in the service layer against the section registry.
    configuration   JSONB       NOT NULL DEFAULT '{}'::jsonb,
    sort_order      INTEGER     NOT NULL DEFAULT 0,
    is_active       BOOLEAN     NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_page_sections_version FOREIGN KEY (page_version_id) REFERENCES page_versions (id) ON DELETE CASCADE,
    CONSTRAINT fk_page_sections_media FOREIGN KEY (media_id) REFERENCES media_files (id) ON DELETE SET NULL,
    CONSTRAINT fk_page_sections_bg FOREIGN KEY (background_media_id) REFERENCES media_files (id) ON DELETE SET NULL,
    CONSTRAINT ck_page_sections_background CHECK (background_style IN ('DEFAULT', 'MUTED', 'DARK', 'ACCENT', 'IMAGE'))
);

CREATE INDEX idx_page_sections_version ON page_sections (page_version_id, sort_order);
